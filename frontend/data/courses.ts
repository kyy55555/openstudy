export type SuggestedStudyStage =
  | "Year 1"
  | "Year 2"
  | "Years 2–3"
  | "Years 3–4"
  | "Graduate";

/**
 * A learner-facing estimate, not an official classification by the university.
 * It is derived conservatively from the verified level and prerequisite chain.
 */
export function suggestedStudyStage(course: Course): SuggestedStudyStage | null {
  if (course.level === "Graduate") return "Graduate";
  if (course.level === "Advanced" || course.level === "Advanced Undergraduate") {
    return "Years 3–4";
  }
  if (course.level === "Undergraduate") return "Years 2–3";
  if (course.level === "Intermediate") return "Year 2";
  if (course.level === "Introductory") {
    return course.prerequisites?.length ? "Year 2" : "Year 1";
  }
  return null;
}

export function courseCode(course: Course): string {
  const parts = course.id.split("-");
  const university = parts[0];
  const rawCode = parts.slice(1).join("-");

  if (university === "mit") {
    return rawCode.replace("-", ".").toUpperCase();
  }
  if (university === "stanford") {
    return rawCode.toUpperCase();
  }
  if (university === "harvard") {
    const harvardCodes: Record<string, string> = {
      cs50x: "CS50x",
      "cs50-python": "CS50P",
      "cs50-ai": "CS50 AI",
      "cs50-web": "CS50W",
      "cs50-sql": "CS50 SQL",
      "cs50-cybersecurity": "CS50 Cybersecurity",
      "cs50-r": "CS50R",
      "cs50-scratch": "CS50 Scratch",
    };
    return harvardCodes[rawCode] ?? rawCode.toUpperCase();
  }
  if (university === "princeton") {
    return rawCode.replace(/^cos/, "COS ").toUpperCase();
  }
  if (university === "cornell" || university === "berkeley") {
    return rawCode.replace(/^([a-z]+)(\d)/, "$1 $2").toUpperCase();
  }
  if (university === "washington") {
    return rawCode.replace(/^cse/, "CSE ").toUpperCase();
  }
  if (university === "tsinghua") {
    return ["computer-graphics", "database-technology"].includes(rawCode) ? "官方公开课" : rawCode.toUpperCase();
  }
  if (university === "pku") {
    return rawCode === "operating-systems" ? "官方课程" : "官方公开课";
  }
  return rawCode.toUpperCase();
}

