type CourseSeed = Omit<
  Course,
  | "titleZh"
  | "descriptionZh"
  | "searchKeywords"
  | "level"
  | "prerequisites"
  | "language"
  | "year"
  | "hasVideos"
  | "hasAssignments"
  | "hasSolutions"
  | "sourceUrl"
  | "verifiedOn"
  | "resources"
> &
  Partial<
    Pick<
      Course,
      | "titleZh"
      | "descriptionZh"
      | "searchKeywords"
      | "level"
      | "prerequisites"
      | "language"
      | "year"
      | "hasVideos"
      | "hasAssignments"
      | "hasSolutions"
      | "sourceUrl"
      | "resources"
    >
  >;

