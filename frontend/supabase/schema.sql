create table if not exists public.course_libraries (
  user_id uuid primary key references auth.users(id) on delete cascade,
  library jsonb not null default '{"progress":{},"favorites":[],"completedResources":[],"studyPlans":{},"lastOpenedResource":null}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.course_libraries enable row level security;

drop policy if exists "Users can read their own course library" on public.course_libraries;
create policy "Users can read their own course library"
on public.course_libraries for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own course library" on public.course_libraries;
create policy "Users can create their own course library"
on public.course_libraries for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own course library" on public.course_libraries;
create policy "Users can update their own course library"
on public.course_libraries for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create or replace function public.save_course_library(
  p_expected_updated_at timestamptz,
  p_library jsonb
)
returns table (
  result_status text,
  result_updated_at timestamptz,
  result_library jsonb
)
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_saved_at timestamptz := clock_timestamp();
begin
  if v_user_id is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if p_expected_updated_at is null then
    insert into public.course_libraries (user_id, library, updated_at)
    values (v_user_id, p_library, v_saved_at)
    on conflict (user_id) do nothing;

    if found then
      return query select 'saved'::text, v_saved_at, p_library;
      return;
    end if;
  else
    update public.course_libraries
    set library = p_library, updated_at = v_saved_at
    where user_id = v_user_id and updated_at = p_expected_updated_at;

    if found then
      return query select 'saved'::text, v_saved_at, p_library;
      return;
    end if;
  end if;

  return query
  select 'conflict'::text, course_libraries.updated_at, course_libraries.library
  from public.course_libraries
  where course_libraries.user_id = v_user_id;
end;
$$;

revoke all on function public.save_course_library(timestamptz, jsonb) from public;
grant execute on function public.save_course_library(timestamptz, jsonb) to authenticated;

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  message text not null check (char_length(message) between 10 and 4000),
  email text check (email is null or char_length(email) <= 320),
  page_url text check (page_url is null or char_length(page_url) <= 2000),
  created_at timestamptz not null default now()
);

alter table public.feedback add column if not exists issue_type text;
alter table public.feedback add column if not exists status text not null default 'new';
alter table public.feedback add column if not exists language text;
alter table public.feedback add column if not exists viewport text;
alter table public.feedback add column if not exists app_version text;

alter table public.feedback drop constraint if exists feedback_issue_type_check;
alter table public.feedback add constraint feedback_issue_type_check check (issue_type is null or issue_type in ('broken-link', 'course-data', 'missing-course', 'study-plan', 'account-sync', 'mobile-accessibility', 'translation', 'account-deletion', 'other'));
alter table public.feedback drop constraint if exists feedback_status_check;
alter table public.feedback add constraint feedback_status_check check (status in ('new', 'reviewing', 'resolved', 'closed'));
alter table public.feedback drop constraint if exists feedback_language_check;
alter table public.feedback add constraint feedback_language_check check (language is null or language in ('en', 'zh'));
alter table public.feedback drop constraint if exists feedback_viewport_check;
alter table public.feedback add constraint feedback_viewport_check check (viewport is null or viewport in ('mobile', 'tablet', 'desktop'));
alter table public.feedback drop constraint if exists feedback_app_version_length_check;
alter table public.feedback add constraint feedback_app_version_length_check check (app_version is null or char_length(app_version) <= 40);

alter table public.feedback enable row level security;

drop policy if exists "Anyone can submit beta feedback" on public.feedback;
create policy "Anyone can submit beta feedback"
on public.feedback for insert
to anon, authenticated
with check (char_length(message) between 10 and 4000);

create index if not exists feedback_created_at_idx on public.feedback (created_at desc);
create index if not exists feedback_status_created_at_idx on public.feedback (status, created_at desc);
create index if not exists feedback_issue_type_created_at_idx on public.feedback (issue_type, created_at desc);
