-- Privacy-minimized first-party product analytics. It stores random browser/session
-- identifiers and bounded product actions, never email addresses, passwords, full
-- URLs, IP addresses, or device fingerprints.
create table if not exists public.product_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in ('course_search', 'goal_route_requested', 'course_opened', 'resource_opened', 'favorite_added', 'favorite_removed', 'study_plan_created', 'study_task_completed', 'signup_completed')),
  anonymous_id uuid not null,
  session_id uuid not null,
  user_id uuid default auth.uid() references auth.users(id) on delete set null,
  course_id text check (course_id is null or char_length(course_id) <= 120),
  resource_type text check (resource_type is null or char_length(resource_type) <= 40),
  search_query text check (search_query is null or char_length(search_query) <= 160),
  numeric_value integer check (numeric_value is null or numeric_value between 0 and 3650),
  language text check (language is null or language in ('en', 'zh')),
  viewport text not null check (viewport in ('mobile', 'tablet', 'desktop')),
  page_path text not null check (char_length(page_path) between 1 and 500 and page_path not like '%?%'),
  created_at timestamptz not null default now()
);

alter table public.product_events enable row level security;

drop policy if exists "Visitors can submit anonymous product events" on public.product_events;
create policy "Visitors can submit anonymous product events"
