-- Open these owner-only views in Supabase Table Editor to inspect daily usage and
-- exact-day retention. No grants are given to website visitors.
create or replace view public.product_daily_summary
with (security_invoker = true)
as
select
  created_at::date as activity_date,
  event_name,
  count(*)::bigint as event_count,
  count(distinct anonymous_id)::bigint as visitor_count,
  count(distinct session_id)::bigint as session_count
from public.product_events
group by created_at::date, event_name;

create or replace view public.product_retention
with (security_invoker = true)
as
with visitor_days as (
  select distinct anonymous_id, created_at::date as activity_date
  from public.product_events
), cohorts as (
  select anonymous_id, min(activity_date) as cohort_date
  from visitor_days
  group by anonymous_id
)
select
  cohorts.cohort_date,
  count(*)::bigint as cohort_size,
  count(*) filter (where exists (select 1 from visitor_days where visitor_days.anonymous_id = cohorts.anonymous_id and visitor_days.activity_date = cohorts.cohort_date + 1))::bigint as day_1_returned,
  count(*) filter (where exists (select 1 from visitor_days where visitor_days.anonymous_id = cohorts.anonymous_id and visitor_days.activity_date = cohorts.cohort_date + 7))::bigint as day_7_returned,
  count(*) filter (where exists (select 1 from visitor_days where visitor_days.anonymous_id = cohorts.anonymous_id and visitor_days.activity_date = cohorts.cohort_date + 14))::bigint as day_14_returned,
  count(*) filter (where exists (select 1 from visitor_days where visitor_days.anonymous_id = cohorts.anonymous_id and visitor_days.activity_date = cohorts.cohort_date + 30))::bigint as day_30_returned
from cohorts
group by cohorts.cohort_date;

revoke all on table public.product_daily_summary from anon, authenticated;
revoke all on table public.product_retention from anon, authenticated;
